_TOWNS = ["郓城县", "东京", "大名府", "青州", "沧州", "蓟州", "登州",
          "江州", "揭阳镇", "华州", "凌州", "高唐州", "曾头市", "独龙冈"]
_OUTCOMES = ["征战阵亡", "病故", "招安后善终", "出家", "隐退江湖", "遇害"]


def _synthetic_columns() -> dict[int, tuple[str, int, int, str]]:
    """虚构列：籍贯 / 上山年份 / 战功数 / 结局。固定种子 → 可复现。"""
    rng = random.Random(20260811)
    out: dict[int, tuple[str, int, int, str]] = {}
    for rank, *_rest in LIANG:
        town = _TOWNS[rng.randrange(len(_TOWNS))]
        year = 1108 + rng.randint(0, 6)
        # 座次越靠前，战功数越高（制造可被聚合查询发现的结构）
        merit = max(1, int(rng.gauss(60 - rank * 0.45, 6)))
        outcome = _OUTCOMES[rng.randrange(len(_OUTCOMES))]
        out[rank] = (town, year, merit, outcome)
    return out


SYNTHETIC = _synthetic_columns()


def rows() -> list[dict]:
    out = []
    for rank, star, nickname, name, group in LIANG:
        town, year, merit, outcome = SYNTHETIC[rank]
        out.append({
            "rank": rank,
            "star_name": star,
            "nickname": nickname,
            "name": name,
            "camp": "天罡星" if rank <= 36 else "地煞星",
            "role_group": group,
            "home_town": town,
            "join_year": year,
            "merit_count": merit,
            "outcome": outcome,
        })
    return out
